    #[test]
    fn test_symmetric_group_s4_has_24_distinct_bijections() {
        // 4! = 24; verify all are distinct and each is a valid bijection.
        let s4 = Permutation::symmetric_group(4);
        assert_eq!(s4.len(), 24, "4! must equal 24");
        let mut sorted = s4.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(sorted.len(), 24, "all 24 permutations must be distinct");
        // Every generated permutation must map {0,1,2,3} onto itself.
        for p in &s4 {
            let mut img: Vec<usize> = (0..4).map(|i| p.apply(i)).collect();
            img.sort();
            assert_eq!(
                img,
                vec![0, 1, 2, 3],
                "each permutation must be a bijection"
            );
        }
    }

    #[test]
    fn test_transpositions_n4_is_choose_2() {
        // C(4,2) = 6 transpositions.
        let trans = Permutation::transpositions(4);
        assert_eq!(trans.len(), 6);
        // Each must be its own inverse (a transposition is an involution).
        for t in &trans {
            assert!(t.compose(t).is_identity());
        }
    }

    #[test]
    fn test_generated_group_matches_order_lcm() {
        // (0 1)(2 3 4): cycle lengths 2 and 3 -> order lcm(2,3)=6.
        // The generated cyclic group must have exactly 6 distinct elements.
        let p = Permutation::new(&[1, 0, 3, 4, 2]);
        assert_eq!(p.order(), 6);
        let grp = p.generated_group();
        let mut distinct = grp.clone();
        distinct.sort();
        distinct.dedup();
        assert_eq!(distinct.len(), 6, "cyclic group size must equal the order");
    }

    // --- Orbit-stabilizer theorem spot-check ---

    #[test]
    fn test_orbit_stabilizer_theorem_s3() {
        // S_3 generated by all transpositions of {0,1,2}.
        let gens = Permutation::transpositions(3);
        let g = group_closure(&gens);
        assert_eq!(g.len(), 6, "|S_3| = 3! = 6");

        let orbit = Permutation::orbit(0, &gens);
        assert_eq!(orbit.len(), 3, "orbit of 0 under S_3 is {{0,1,2}}");

        let stab_gens = Permutation::stabilizer_generators(0, &gens);
        let stab = group_closure(&stab_gens);

        // Every stabilizer element must fix 0.
        for s in &stab {
            assert_eq!(s.apply(0), 0, "stabilizer element must fix 0");
        }

        // Orbit-stabilizer theorem: |G| = |orbit(i)| * |stab(i)|.
        assert_eq!(
            orbit.len() * stab.len(),
            g.len(),
            "|orbit| * |stab| must equal |G|"
        );
        assert_eq!(stab.len(), 2, "stabilizer of 0 in S_3 has order 2");
    }

