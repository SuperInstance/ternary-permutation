    // --- Regression: order() must not panic on high-degree permutations ---

    #[test]
    fn test_order_high_degree_no_panic() {
        // Product of cycles of length 4, 5, 7, 9 on 25 elements.
        // order = lcm(4,5,7,9) = 1260, which exceeds the old n^2+1=626 bound.
        let n = 25usize;
        let mut images: Vec<usize> = (0..n).collect();
        rotate_cycle(&mut images, 0, 4);
        rotate_cycle(&mut images, 4, 5);
        rotate_cycle(&mut images, 9, 7);
        rotate_cycle(&mut images, 16, 9);
        let p = Permutation::new(&images);
        assert_eq!(p.order(), 1260);
    }

    fn rotate_cycle(img: &mut [usize], start: usize, len: usize) {
        // Turn img[start..start+len] into a single cycle: start->start+1->...
        let tmp = img[start];
        for i in 0..len - 1 {
            img[start + i] = img[start + i + 1];
        }
        img[start + len - 1] = tmp;
    }

