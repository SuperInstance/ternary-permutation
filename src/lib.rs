//! Permutation groups acting on ternary vectors.
//!
//! Provides permutation composition, inverse, orbit computation, stabilizer groups,
//! cycle decomposition, action on ternary tuples, and symmetric group generators.
//! All values are modulo 3 (ternary: 0, 1, 2).

#![forbid(unsafe_code)]

/// A permutation represented as a mapping of indices.
/// perm[i] = j means element at position i is sent to position j.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Permutation {
    /// The mapping: images[i] = where element i goes
    images: Vec<usize>,
}

impl Permutation {
    /// Create a permutation from a slice of images.
    /// images[i] = j means i maps to j.
    /// Panics if not a valid permutation of {0, ..., n-1}.
    pub fn new(images: &[usize]) -> Self {
        let n = images.len();
        let mut seen = vec![false; n];
        for &v in images {
            if v >= n || seen[v] {
                panic!(
                    "Invalid permutation: not a bijection of {{0,...,{}}}",
                    n - 1
                );
            }
            seen[v] = true;
        }
        Self {
            images: images.to_vec(),
        }
    }

    /// Identity permutation of size n.
    pub fn identity(n: usize) -> Self {
        Self {
            images: (0..n).collect(),
        }
    }

    /// Number of elements this permutation acts on.
    pub fn len(&self) -> usize {
        self.images.len()
    }

    /// Returns true if this permutation acts on zero elements (the empty
    /// permutation of degree 0).
    pub fn is_empty(&self) -> bool {
        self.images.is_empty()
    }

    /// Returns true if this is the identity permutation.
    pub fn is_identity(&self) -> bool {
        self.images.iter().enumerate().all(|(i, &v)| i == v)
    }

    /// Apply permutation: returns where element i goes.
    pub fn apply(&self, i: usize) -> usize {
        self.images[i]
    }

    /// Compose self with other: (self ∘ other)(i) = self(other(i)).
    pub fn compose(&self, other: &Permutation) -> Permutation {
        assert_eq!(
            self.len(),
            other.len(),
            "Permutations must have same degree"
        );
        let images: Vec<usize> = (0..self.len())
            .map(|i| self.apply(other.apply(i)))
            .collect();
        Permutation { images }
    }

    /// Compute the inverse permutation.
    pub fn inverse(&self) -> Permutation {
        let n = self.len();
        let mut inv = vec![0; n];
        for i in 0..n {
            inv[self.apply(i)] = i;
        }
        Permutation { images: inv }
    }

    /// Compute the order (smallest positive k such that σ^k = identity).
    ///
    /// The order equals the least common multiple of the cycle lengths, which is
    /// computed exactly and in O(n) time. This avoids the previous approach of
    /// iterating `p, p², p³, …` up to an `n² + 1` bound, which panicked
    /// spuriously for valid permutations whose order exceeds `n² + 1` (first
    /// occurring at degree 25, e.g. a product of cycles of length 4·5·7·9 has
    /// order 1260 > 25² + 1 = 626).
    pub fn order(&self) -> usize {
        let cycles = self.cycle_decomposition();
        if cycles.is_empty() {
            return 1; // identity: every element is a fixed point (no cycles > 1)
        }
        cycles.iter().map(|c| c.len()).fold(1usize, lcm)
    }

    /// Cycle decomposition. Returns a vector of cycles, each cycle is a Vec<usize>.
    pub fn cycle_decomposition(&self) -> Vec<Vec<usize>> {
        let n = self.len();
        let mut visited = vec![false; n];
        let mut cycles = Vec::new();
        for start in 0..n {
            if visited[start] {
                continue;
            }
            let mut cycle = Vec::new();
            let mut current = start;
            loop {
                if visited[current] {
                    break;
                }
                visited[current] = true;
                cycle.push(current);
                current = self.apply(current);
            }
            if cycle.len() > 1 {
                cycles.push(cycle);
            }
        }
        cycles
    }

    /// Compute the orbit of element i under the group generated by the given permutations.
    pub fn orbit(i: usize, generators: &[Permutation]) -> Vec<usize> {
        let n = if generators.is_empty() {
            return vec![i];
        } else {
            generators[0].len()
        };
        let mut orbit = vec![false; n];
        let mut stack = vec![i];
        orbit[i] = true;
        while let Some(current) = stack.pop() {
            for g in generators {
                let next = g.apply(current);
                if !orbit[next] {
                    orbit[next] = true;
                    stack.push(next);
                }
            }
        }
        (0..n).filter(|&i| orbit[i]).collect()
    }

    /// Compute the stabilizer of element i using the orbit-stabilizer theorem approach.
    /// Returns generators for the stabilizer subgroup.
    pub fn stabilizer_generators(i: usize, generators: &[Permutation]) -> Vec<Permutation> {
        // Use Schreier's lemma: for each generator g and each orbit element o,
        // the Schreier generator is (representative(o)) * g * (representative(g(o)))^(-1)
        let orbit = Self::orbit(i, generators);
        let n = if generators.is_empty() {
            return vec![];
        } else {
            generators[0].len()
        };

        // Build representative map: for each element in orbit, find a word that sends i to it
        let mut rep = vec![None::<Permutation>; n];
        rep[i] = Some(Permutation::identity(n));
        let mut queue = vec![i];
        let mut in_queue = vec![false; n];
        in_queue[i] = true;

        while let Some(current) = queue.pop() {
            let rep_current = rep[current].clone().unwrap();
            for g in generators {
                let next = g.apply(current);
                if rep[next].is_none() {
                    rep[next] = Some(g.compose(&rep_current));
                    if !in_queue[next] {
                        in_queue[next] = true;
                        queue.push(next);
                    }
                }
            }
        }

        // Schreier generators
        let mut stab_gens = Vec::new();
        for &o in &orbit {
            for g in generators {
                let go = g.apply(o);
                if let (Some(ref rep_o), Some(ref rep_go)) = (&rep[o], &rep[go]) {
                    let sg = rep_go.inverse().compose(&g.compose(rep_o));
                    if !sg.is_identity() {
                        stab_gens.push(sg);
                    }
                }
            }
        }
        stab_gens
    }

    /// Act on a ternary vector (values 0, 1, 2) by permuting positions.
    pub fn act_on_ternary(&self, v: &[u8]) -> Vec<u8> {
        assert_eq!(self.len(), v.len());
        let mut result = vec![0u8; v.len()];
        for i in 0..v.len() {
            result[self.apply(i)] = v[i];
        }
        result
    }

    /// Generate all transpositions (i, j) for i < j in {0, ..., n-1}.
    pub fn transpositions(n: usize) -> Vec<Permutation> {
        let mut trans = Vec::new();
        for i in 0..n {
            for j in (i + 1)..n {
                let mut images: Vec<usize> = (0..n).collect();
                images.swap(i, j);
                trans.push(Permutation { images });
            }
        }
        trans
    }

    /// Generate the symmetric group S_n as all permutations of {0, ..., n-1}.
    pub fn symmetric_group(n: usize) -> Vec<Permutation> {
        if n == 0 {
            return vec![Permutation::identity(0)];
        }
        let mut result = Vec::new();
        let mut images: Vec<usize> = (0..n).collect();
        loop {
            result.push(Permutation {
                images: images.clone(),
            });
            // Next permutation (lexicographic)
            if !next_perm(&mut images) {
                break;
            }
        }
        result
    }

    /// Generate the cyclic group generated by this permutation.
    pub fn generated_group(&self) -> Vec<Permutation> {
        let ord = self.order();
        let mut group = Vec::with_capacity(ord);
        let mut current = Permutation::identity(self.len());
        for _ in 0..ord {
            group.push(current.clone());
            current = self.compose(&current);
        }
        group
    }

    /// Sign of the permutation (+1 or -1).
    pub fn sign(&self) -> i32 {
        let cycles = self.cycle_decomposition();
        let mut s = 1i32;
        for c in &cycles {
            if c.len() % 2 == 0 {
                s *= -1;
            }
        }
        s
    }

    /// Compose with another permutation, returning a new permutation acting on
    /// ternary tuples (cross product {0,1,2}^n).
    /// This applies the permutation to all possible ternary vectors.
    pub fn action_on_ternary_tuples(&self) -> Vec<(Vec<u8>, Vec<u8>)> {
        let n = self.len();
        let total = 3usize.pow(n as u32);
        let mut pairs = Vec::with_capacity(total);
        for idx in 0..total {
            let v = Self::index_to_ternary(idx, n);
            let w = self.act_on_ternary(&v);
            pairs.push((v, w));
        }
        pairs
    }

    /// Convert an index to a ternary vector of length n.
    pub fn index_to_ternary(mut idx: usize, n: usize) -> Vec<u8> {
        let mut v = vec![0u8; n];
        for i in (0..n).rev() {
            v[i] = (idx % 3) as u8;
            idx /= 3;
        }
        v
    }

    /// Convert a ternary vector to an index.
    pub fn ternary_to_index(v: &[u8]) -> usize {
        let mut idx = 0;
        for &val in v {
            idx = idx * 3 + val as usize;
        }
        idx
    }
}

fn next_perm(arr: &mut [usize]) -> bool {
    let n = arr.len();
    if n < 2 {
        return false;
    }
    // Find largest k such that arr[k] < arr[k+1]
    let mut k = n as isize - 2;
    while k >= 0 && arr[k as usize] >= arr[k as usize + 1] {
        k -= 1;
    }
    if k < 0 {
        return false;
    }
    let k = k as usize;
    // Find largest l > k such that arr[k] < arr[l]
    let mut l = n - 1;
    while arr[k] >= arr[l] {
        l -= 1;
    }
    arr.swap(k, l);
    arr[k + 1..].reverse();
    true
}

/// Greatest common divisor (Euclidean algorithm).
fn gcd(mut a: usize, mut b: usize) -> usize {
    while b != 0 {
        let t = b;
        b = a % b;
        a = t;
    }
    a
}

/// Least common multiple. Returns 0 if either argument is 0.
fn lcm(a: usize, b: usize) -> usize {
    if a == 0 || b == 0 {
        0
    } else {
        a / gcd(a, b) * b
    }
}

